import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const sources = [
  'css/style.css',
  'css/brand.css',
  'css/hero-theme.css',
  'css/gtmetrix-color-system.css',
  'css/desktop-header-canvas-fix.css',
  'css/marketing.css',
  'css/product-pages.css',
  'css/regional-performance.css',
  'css/unified-matte-layout.css',
  'css/marketing-infrastructure-banner.css',
  'css/homepage-mobile-cleanup.css',
  'css/pan-african-intelligence.css',
  'css/workflow-showcase.css',
  'css/get-started-banner.css'
];

const chunks = [];
for (const path of sources) {
  const source = (await readFile(resolve(path), 'utf8'))
    .replace(/^\uFEFF/, '')
    .replace(/^\s*@charset\s+[^;]+;\s*/i, '');
  if (/^\s*@import\b/im.test(source)) {
    throw new Error(`Nested @import is not supported in ${path}`);
  }
  chunks.push(`\n/* ---- ${path} ---- */\n${source}\n`);
}
const output =
  '/* Generated by scripts/build-legacy-home-css.mjs. Source order matches the historical @import chain. */\n' +
  '@layer legacy {\n' + chunks.join('\n') + '\n}\n';
await writeFile(resolve('css/legacy-home.css'), output);
console.log(`Generated css/legacy-home.css from ${sources.length} legacy stylesheets (${output.length} bytes).`);
