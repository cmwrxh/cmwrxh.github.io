CREATE OR REPLACE FUNCTION public.check_ip_rate_limit(
  p_ip_address text, p_endpoint text, p_max_requests integer DEFAULT 5,
  p_window_minutes integer DEFAULT 60
) RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $function$
DECLARE
  v_record public.api_rate_limits%rowtype;
  v_now timestamptz := now();
  v_window_start timestamptz;
BEGIN
  SELECT * INTO v_record FROM public.api_rate_limits
   WHERE ip_address = p_ip_address AND endpoint = p_endpoint FOR UPDATE;
  IF NOT FOUND THEN
    INSERT INTO public.api_rate_limits (ip_address, endpoint, request_count, window_started_at)
    VALUES (p_ip_address, p_endpoint, 1, v_now);
    RETURN true;
  END IF;
  v_window_start := v_record.window_started_at + make_interval(mins => p_window_minutes);
  IF v_now >= v_window_start THEN
    UPDATE public.api_rate_limits SET request_count=1, window_started_at=v_now WHERE id=v_record.id;
    RETURN true;
  END IF;
  IF v_record.request_count >= p_max_requests THEN RETURN false; END IF;
  UPDATE public.api_rate_limits SET request_count=request_count+1 WHERE id=v_record.id;
  RETURN true;
END;
$function$;

CREATE OR REPLACE FUNCTION public.check_rate_limit(client_ip inet, max_requests integer DEFAULT 60)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $function$
DECLARE current_count integer; window_start timestamptz;
BEGIN
  SELECT request_count, window_started_at INTO current_count, window_start
    FROM public.api_rate_limits WHERE ip=client_ip FOR UPDATE;
  IF NOT FOUND THEN
    INSERT INTO public.api_rate_limits (ip, request_count, window_started_at)
    VALUES (client_ip, 1, now());
    RETURN true;
  END IF;
  IF now() >= window_start + interval '1 minute' THEN
    UPDATE public.api_rate_limits SET request_count=1, window_started_at=now() WHERE ip=client_ip;
    RETURN true;
  END IF;
  IF current_count >= max_requests THEN RETURN false; END IF;
  UPDATE public.api_rate_limits SET request_count=request_count+1 WHERE ip=client_ip;
  RETURN true;
END;
$function$;

CREATE OR REPLACE FUNCTION public.check_rate_limit(
  client_ip text, client_endpoint text DEFAULT '/api/ip-lookup', max_requests integer DEFAULT 60
) RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $function$
DECLARE current_count integer; window_start timestamptz;
BEGIN
  SELECT request_count, window_started_at INTO current_count, window_start
    FROM public.api_rate_limits WHERE ip_address=client_ip AND endpoint=client_endpoint FOR UPDATE;
  IF NOT FOUND THEN
    INSERT INTO public.api_rate_limits (ip_address, endpoint, request_count, window_started_at)
    VALUES (client_ip, client_endpoint, 1, now());
    RETURN true;
  END IF;
  IF now() >= window_start + interval '1 minute' THEN
    UPDATE public.api_rate_limits SET request_count=1, window_started_at=now()
     WHERE ip_address=client_ip AND endpoint=client_endpoint;
    RETURN true;
  END IF;
  IF current_count >= max_requests THEN RETURN false; END IF;
  UPDATE public.api_rate_limits SET request_count=request_count+1
   WHERE ip_address=client_ip AND endpoint=client_endpoint;
  RETURN true;
END;
$function$;

CREATE OR REPLACE FUNCTION public.lookup_ip(ip_address inet)
RETURNS TABLE(prefix cidr, asn bigint, network_name text, is_mobile boolean, confidence text,
              carrier_name text, mcc text, mnc text, country_name text, country_code text)
LANGUAGE sql SECURITY DEFINER SET search_path TO 'public'
AS $function$
  SELECT r.prefix, r.asn, r.network_name, r.is_mobile, r.confidence,
         c.name, c.mcc, c.mnc, co.name, co.country_code
    FROM public.ip_ranges r
    LEFT JOIN public.carriers c ON r.carrier_id=c.id
    LEFT JOIN public.countries co ON r.country_id=co.id
   WHERE ip_address <<= r.prefix
   ORDER BY masklen(r.prefix) DESC LIMIT 1;
$function$;

CREATE OR REPLACE FUNCTION public.get_ip_ranges_due_for_verification(batch_size integer DEFAULT 25)
RETURNS TABLE(ip_range_id uuid, prefix cidr, asn bigint, network_name text, carrier_id uuid,
              country_id uuid, verification_status text, last_verified timestamptz, next_review_at timestamptz)
LANGUAGE sql SECURITY DEFINER SET search_path TO 'public'
AS $function$
  SELECT r.id, r.prefix, r.asn, r.network_name, r.carrier_id, r.country_id,
         r.verification_status, r.last_verified, r.next_review_at
    FROM public.ip_ranges r
   WHERE r.verification_status <> 'disputed'
     AND (r.next_review_at IS NULL OR r.next_review_at <= now())
   ORDER BY r.next_review_at ASC NULLS FIRST, r.last_verified ASC NULLS FIRST
   LIMIT greatest(1, least(batch_size, 100));
$function$;

CREATE OR REPLACE FUNCTION public.rum_stats(p_site uuid, p_days integer, p_group text)
RETURNS TABLE(label text, n bigint, ttfb_n bigint, ttfb_p50 real, ttfb_p95 real, ttfb_p99 real,
 lcp_n bigint, lcp_p50 real, lcp_p95 real, lcp_p99 real, inp_n bigint, inp_p50 real, inp_p95 real,
 inp_p99 real, load_n bigint, load_p50 real, load_p95 real, load_p99 real, cls_avg numeric)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path TO 'public'
AS $function$
DECLARE label_expr text;
BEGIN
  label_expr := CASE p_group
    WHEN 'network' THEN 'coalesce((select display_name from mno_map where lower(coalesce(r.isp, '''')) like ''%'' || match || ''%'' limit 1), r.isp)'
    WHEN 'page_url' THEN 'r.page_url'
    WHEN 'isp' THEN 'r.isp'
    WHEN 'device_type' THEN 'r.device_type'
    WHEN 'connection_type' THEN 'r.connection_type'
    ELSE 'r.country'
  END;
  RETURN QUERY EXECUTE format(
    'select coalesce(%s, ''Unknown'') as label, count(*) as n,
     count(ttfb_ms) as ttfb_n, (percentile_cont(0.5) within group (order by ttfb_ms))::real,
     (percentile_cont(0.95) within group (order by ttfb_ms))::real,
     (percentile_cont(0.99) within group (order by ttfb_ms))::real,
     count(lcp_ms) as lcp_n, (percentile_cont(0.5) within group (order by lcp_ms))::real,
     (percentile_cont(0.95) within group (order by lcp_ms))::real,
     (percentile_cont(0.99) within group (order by lcp_ms))::real,
     count(inp_ms) as inp_n, (percentile_cont(0.5) within group (order by inp_ms))::real,
     (percentile_cont(0.95) within group (order by inp_ms))::real,
     (percentile_cont(0.99) within group (order by inp_ms))::real,
     count(load_ms) as load_n, (percentile_cont(0.5) within group (order by load_ms))::real,
     (percentile_cont(0.95) within group (order by load_ms))::real,
     (percentile_cont(0.99) within group (order by load_ms))::real,
     round(avg(cls)::numeric, 3) as cls_avg
     from rum_events r where r.site_id=$1 and r.received_at > now()-make_interval(days => $2)
     group by 1 order by n desc limit 100', label_expr
  ) USING p_site, p_days;
END;
$function$;

